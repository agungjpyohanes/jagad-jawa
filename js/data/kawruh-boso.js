let currentKawruhTab = 'kembang';
let kawruhSearchQuery = '';

export function setKawruhTab(tabKey) {
  currentKawruhTab = tabKey;
  renderKawruhBosoUI();
}

export function onKawruhSearch(query) {
  kawruhSearchQuery = (query || '').toLowerCase().trim();
  renderKawruhGridContent();
}

export function renderKawruhBosoUI(containerId = 'kawruhBosoContainer') {
  const container = document.getElementById(containerId);
  if (!container) return;

  const tabs = [
    { key: 'kembang', label: 'Arane Kembang', icon: 'fa-seedling', count: KAWRUH_BOSO_DATA.kembang.length },
    { key: 'kewan', label: 'Arane Anak Kewan', icon: 'fa-paw', count: KAWRUH_BOSO_DATA.kewan.length },
    { key: 'jarwosodik', label: 'Jarwosodik (Akronim)', icon: 'fa-quote-left', count: KAWRUH_BOSO_DATA.jarwosodik.length },
    { key: 'candrane', label: 'Candrane Awak (Pujian Raga)', icon: 'fa-person', count: KAWRUH_BOSO_DATA.candrane.length }
  ];

  container.innerHTML = `
    <div class="space-y-6">
      <!-- Header -->
      <div class="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-sogan-800 pb-3">
        <div>
          <span class="text-[10px] font-mono uppercase text-prada tracking-widest font-bold block flex items-center gap-1.5">
            <i class="fa-solid fa-feather-pointed"></i> Paramasastra &amp; Unggah-Ungguh
          </span>
          <h3 class="font-marcellus text-xl sm:text-2xl font-bold gold-gradient-text">
            Kawruh Basa Jawa Adiluhung
          </h3>
          <p class="text-xs text-sogan-300">
            Kekayaan kosakata tradisional: arane kembang, arane anak kewan, jarwosodik, sarta candrane awak.
          </p>
        </div>

        <!-- Kolom Pencarian -->
        <div class="relative w-full sm:w-64">
          <input
            type="text"
            id="kawruhSearchInput"
            placeholder="Cari kata / istilah..."
            value="${kawruhSearchQuery}"
            oninput="window.onKawruhSearch && window.onKawruhSearch(this.value)"
            class="w-full pl-9 pr-4 py-2 rounded-xl bg-keraton border border-sogan-700 text-xs text-sogan-100 placeholder-sogan-500 focus:border-prada outline-none transition"
          />
          <i class="fa-solid fa-magnifying-glass absolute left-3 top-2.5 text-xs text-sogan-400 pointer-events-none"></i>
        </div>
      </div>

      <!-- Tab Buttons -->
      <div class="flex flex-wrap items-center gap-2">
        ${tabs.map(t => {
          const isActive = currentKawruhTab === t.key;
          return `
            <button
              type="button"
              onclick="window.setKawruhTab && window.setKawruhTab('${t.key}')"
              class="px-4 py-2 rounded-xl text-xs font-semibold flex items-center gap-2 transition cursor-pointer ${isActive ? 'bg-gradient-to-r from-sogan-600 to-prada text-keraton font-bold shadow' : 'bg-sogan-950 border border-sogan-800 text-sogan-300 hover:text-prada'}">
              <i class="fa-solid ${t.icon}"></i>
              <span>${t.label}</span>
              <span class="text-[10px] font-mono px-1.5 py-0.2 rounded ${isActive ? 'bg-keraton/30 text-keraton' : 'bg-sogan-900 text-sogan-400'}">${t.count}</span>
            </button>
          `;
        }).join('')}
      </div>

      <!-- Grid Cards -->
      <div id="kawruhGridContent" class="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-3.5">
        <!-- Rendered by renderKawruhGridContent() -->
      </div>
    </div>
  `;

  renderKawruhGridContent();
}

function renderKawruhGridContent() {
  const container = document.getElementById('kawruhGridContent');
  if (!container) return;

  const rawList = KAWRUH_BOSO_DATA[currentKawruhTab] || [];
  const q = kawruhSearchQuery;

  const filtered = rawList.filter(item => {
    if (!q) return true;
    const matchNama = (item.nama || item.bagian || '').toLowerCase().includes(q);
    const matchArane = (item.arane || item.kepanjangan || item.candra || '').toLowerCase().includes(q);
    const matchTeges = (item.teges || '').toLowerCase().includes(q);
    return matchNama || matchArane || matchTeges;
  });

  if (filtered.length === 0) {
    container.innerHTML = `
      <div class="col-span-full p-8 text-center text-xs text-sogan-400">
        <i class="fa-solid fa-circle-question text-xl mb-2 text-prada/60 block"></i>
        Mboten wonten tetembungan ingkang jumbuh kaliyan padosan "${q}".
      </div>
    `;
    return;
  }

  container.innerHTML = filtered.map((item, idx) => {
    if (currentKawruhTab === 'kembang') {
      return `
        <div class="p-4 rounded-2xl bg-gradient-to-br from-[#121724] to-[#0A0D15] border border-sogan-800/80 hover:border-prada/50 transition shadow space-y-2">
          <div class="flex items-center justify-between text-xs">
            <span class="text-sogan-400 font-mono text-[11px]">Kembang ${item.nama}</span>
            <span class="px-2 py-0.5 rounded-full bg-emerald-950 text-emerald-300 border border-emerald-800/60 font-mono font-bold text-[10px]">Kembang</span>
          </div>
          <div class="text-base font-marcellus font-bold gold-gradient-text">
            Arane: ${item.arane}
          </div>
          <p class="text-[11.5px] text-sogan-300 leading-relaxed">${item.teges}</p>
        </div>
      `;
    } else if (currentKawruhTab === 'kewan') {
      return `
        <div class="p-4 rounded-2xl bg-gradient-to-br from-[#121724] to-[#0A0D15] border border-sogan-800/80 hover:border-prada/50 transition shadow space-y-2">
          <div class="flex items-center justify-between text-xs">
            <span class="text-sogan-400 font-mono text-[11px]">Anak ${item.nama}</span>
            <span class="px-2 py-0.5 rounded-full bg-amber-950 text-amber-300 border border-amber-800/60 font-mono font-bold text-[10px]">Anak Kewan</span>
          </div>
          <div class="text-base font-marcellus font-bold gold-gradient-text">
            Arane: ${item.arane}
          </div>
          <p class="text-[11.5px] text-sogan-300 leading-relaxed">${item.teges}</p>
        </div>
      `;
    } else if (currentKawruhTab === 'jarwosodik') {
      return `
        <div class="p-4 rounded-2xl bg-gradient-to-br from-[#121724] to-[#0A0D15] border border-sogan-800/80 hover:border-prada/50 transition shadow space-y-2">
          <div class="flex items-center justify-between text-xs">
            <span class="text-prada font-bold font-mono text-[12px]">${item.nama}</span>
            <span class="px-2 py-0.5 rounded-full bg-purple-950 text-purple-300 border border-purple-800/60 font-mono text-[10px]">Othak-Athik</span>
          </div>
          <div class="text-xs font-mono text-amber-200 font-semibold bg-black/40 p-2 rounded-xl border border-white/5">
            = ${item.kepanjangan}
          </div>
          <p class="text-[11.5px] text-sogan-300 leading-relaxed">${item.teges}</p>
        </div>
      `;
    } else {
      return `
        <div class="p-4 rounded-2xl bg-gradient-to-br from-[#121724] to-[#0A0D15] border border-sogan-800/80 hover:border-prada/50 transition shadow space-y-2">
          <div class="flex items-center justify-between text-xs">
            <span class="text-prada font-bold text-[11px]">${item.bagian}</span>
            <span class="px-2 py-0.5 rounded-full bg-sky-950 text-sky-300 border border-sky-800/60 font-mono text-[10px]">Pangrumpaka</span>
          </div>
          <div class="text-sm font-marcellus font-bold text-amber-200">
            ${item.candra}
          </div>
          <p class="text-[11.5px] text-sogan-300 leading-relaxed">${item.teges}</p>
        </div>
      `;
    }
  }).join('');
}

if (typeof window !== 'undefined') {
  window.setKawruhTab = setKawruhTab;
  window.onKawruhSearch = onKawruhSearch;
  window.renderKawruhBosoUI = renderKawruhBosoUI;
}
