export function selectTumpengHotspot(index) {
  const item = TUMPENG_UBARAMPE.find(x => x.id === Number(index));
  if (!item) return;

  // Highlight hotspot buttons
  document.querySelectorAll('.tumpeng-hotspot-btn').forEach(btn => {
    if (Number(btn.dataset.hotspot) === item.id) {
      btn.classList.add('active', 'scale-110', 'ring-4', 'ring-prada');
    } else {
      btn.classList.remove('active', 'scale-110', 'ring-4', 'ring-prada');
    }
  });

  // Update Detail Card
  const elNum = document.getElementById('tumpengDetailNum');
  const elTitle = document.getElementById('tumpengDetailTitle');
  const elPos = document.getElementById('tumpengDetailPos');
  const elSimbol = document.getElementById('tumpengDetailSimbol');
  const elDesc = document.getElementById('tumpengDetailDesc');
  const elMakna = document.getElementById('tumpengDetailMakna');
  const elIcon = document.getElementById('tumpengDetailIcon');

  if (elNum) elNum.textContent = item.id;
  if (elTitle) elTitle.textContent = item.nama;
  if (elPos) elPos.textContent = `${item.posisi} · ${item.warna}`;
  if (elSimbol) elSimbol.textContent = item.simbol;
  if (elDesc) elDesc.textContent = item.deskripsi;
  if (elMakna) elMakna.textContent = item.makna;
  if (elIcon) elIcon.className = `fa-solid ${item.icon} text-prada text-lg`;

  // Animation pulse
  const card = document.getElementById('tumpengDetailCard');
  if (card) {
    card.classList.remove('animate-fadeIn');
    void card.offsetWidth; // trigger reflow
    card.classList.add('animate-fadeIn');
  }
}

export function selectTumpengWarna(key) {
  const data = TUMPENG_WARNA[key];
  if (!data) return;

  document.querySelectorAll('.tumpeng-warna-btn').forEach(btn => {
    if (btn.dataset.warna === key) {
      btn.classList.add('border-prada', 'bg-prada/20', 'text-prada-light');
    } else {
      btn.classList.remove('border-prada', 'bg-prada/20', 'text-prada-light');
    }
  });

  const elTitle = document.getElementById('tumpengWarnaTitle');
  const elBadge = document.getElementById('tumpengWarnaBadge');
  const elArah = document.getElementById('tumpengWarnaArah');
  const elNafsu = document.getElementById('tumpengWarnaNafsu');
  const elSedulur = document.getElementById('tumpengWarnaSedulur');
  const elUnsur = document.getElementById('tumpengWarnaUnsur');
  const elWatak = document.getElementById('tumpengWarnaWatak');
  const elFilosofi = document.getElementById('tumpengWarnaFilosofi');
  const elBahan = document.getElementById('tumpengWarnaBahan');
  const card = document.getElementById('tumpengWarnaCard');

  if (elTitle) elTitle.textContent = data.nama;
  if (elBadge) {
    elBadge.className = `px-3 py-1 rounded-full text-[11px] font-bold border ${data.warnaBadge}`;
    elBadge.textContent = data.arah;
  }
  if (elArah) elArah.textContent = data.arah;
  if (elNafsu) elNafsu.textContent = data.nafsu;
  if (elSedulur) elSedulur.textContent = data.sedulur;
  if (elUnsur) elUnsur.textContent = data.unsur;
  if (elWatak) elWatak.textContent = data.watak;
  if (elFilosofi) elFilosofi.textContent = data.filosofi;
  if (elBahan) elBahan.textContent = data.bahan;

  if (card) {
    card.className = `p-6 rounded-2xl border bg-gradient-to-br transition-all duration-300 shadow-xl ${data.bgCard}`;
  }
}

// Global Browser Window Exports
if (typeof window !== 'undefined') {
  window.TUMPENG_UBARAMPE = TUMPENG_UBARAMPE;
  window.TUMPENG_WARNA = TUMPENG_WARNA;
  window.selectTumpengHotspot = selectTumpengHotspot;
  window.selectTumpengWarna = selectTumpengWarna;

  // Auto-init when tab switches to tumpeng
  window.addEventListener('tab-switched', (e) => {
    if (e.detail && e.detail.tabId === 'tumpeng') {
      selectTumpengHotspot(1);
      selectTumpengWarna('ijo');
    }
  });
}

if (typeof module !== 'undefined' && module.exports) {
  module.exports = {
    TUMPENG_UBARAMPE,
    TUMPENG_WARNA,
    selectTumpengHotspot,
    selectTumpengWarna
  };
}
